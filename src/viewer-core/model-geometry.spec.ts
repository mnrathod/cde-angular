/**
 * Reading the geometry container.
 *
 * The central fixture is **bytes the conversion service actually produced**,
 * not bytes this file made up. A reader and a writer tested separately against
 * the same assumption both pass while disagreeing with each other; the only
 * thing that catches that is running one against the other's output. The same
 * reasoning put the real demo host into `protocol-conversation.spec.ts`.
 *
 * Its header happens to be 319 bytes, so the 4-byte alignment padding is one
 * byte rather than zero — the case a round number would quietly skip.
 */
import { describe, expect, it } from 'vitest';

import {
  ModelGeometryFormatError,
  decodeGeometryContainer,
} from './model-geometry';

/**
 * Generated by `encode_geometry_container` in converter/app.py, from two
 * synthetic buckets: IfcWall with 4 vertices and 2 triangles, IfcWindow with
 * 3 vertices and 1 triangle. Regenerate this if the container layout changes
 * — that is the point of it.
 */
